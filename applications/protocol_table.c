const od_sync_t *protocol_od_sync_table(uint16_t *count)
{
    if (count) {
        *count = ARRAY_SIZE(g_od_sync_table);
    }

    return g_od_sync_table;
}

const reg_def_t *protocol_reg_def_table(uint16_t *count)
{
    if (count) {
        *count = ARRAY_SIZE(g_reg_def_table);
    }

    return g_reg_def_table;
}

const reg_def_t *protocol_reg_def_find(uint16_t addr)
{
    uint16_t count;
    const reg_def_t *table = protocol_reg_def_table(&count);

    for (uint16_t i = 0; i < count; i++) {
        if (addr >= table[i].addr_start && addr <= table[i].addr_end) {
            return &table[i];
        }
    }

    return NULL;
}
